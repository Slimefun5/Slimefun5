"""Harvest entity and material display names from Mojang's client language files.

Run by hand; commit the output. CI must never depend on Mojang's CDN at build time.
The locale files are the unpacked assets/minecraft/lang/*.json from the misode/mcmeta repo
(branch "assets", sparse checkout of assets/minecraft/lang), not fetched from Mojang directly.

Usage: python harvest_vanilla.py <dir-with-locale-json> <core-languages-dir>
"""
import io, json, os, sys

# Minecraft locale -> Slimefun language id. Only ids Slimefun actually ships.
LOCALES = {
    "en_us": "en", "de_de": "de", "fr_fr": "fr", "es_es": "es", "it_it": "it",
    "ru_ru": "ru", "pl_pl": "pl", "uk_ua": "uk", "be_by": "be", "sv_se": "sv",
    "nl_nl": "nl", "da_dk": "da", "fi_fi": "fi", "no_no": "no", "cs_cz": "cs",
    "ro_ro": "ro", "bg_bg": "bg", "pt_pt": "pt", "pt_br": "pt-BR", "hu_hu": "hu",
    "hr_hr": "hr", "lv_lv": "lv", "el_gr": "el", "sk_sk": "sk", "vi_vn": "vi",
    "id_id": "id", "zh_cn": "zh-CN", "zh_tw": "zh-TW", "ko_kr": "ko", "he_il": "he",
    "ar_sa": "ar", "tr_tr": "tr", "fa_ir": "fa", "sr_sp": "sr", "af_za": "af",
    "ms_my": "ms", "th_th": "th", "mk_mk": "mk", "fil_ph": "tl", "lt_lt": "lt",
    "si_lk": "si-LK", "ja_jp": "ja",
}

DEAD_LANGUAGE_DIRECTORIES = {"hi", "zh"}


def shipped_languages(langs_dir):
    """Language ids from the directories that exist, independent of LOCALES so a missing mapping is reported."""
    return {name for name in os.listdir(langs_dir)
            if os.path.isdir(os.path.join(langs_dir, name)) and name not in DEAD_LANGUAGE_DIRECTORIES}


def quote(value):
    value = " ".join(value.split())
    return "'" + value.replace("'", "''") + "'"


def harvest(source):
    """One locale json -> ({entity path: name}, {material path: name})."""
    entities, materials = {}, {}
    for key, value in source.items():
        if key.startswith("entity.minecraft."):
            path = key[len("entity.minecraft."):]
            if "." not in path:
                entities[path] = value
        elif key.startswith("block.minecraft."):
            path = key[len("block.minecraft."):]
            if "." not in path:
                materials.setdefault(path, value)
        elif key.startswith("item.minecraft."):
            path = key[len("item.minecraft."):]
            if "." not in path:
                materials[path] = value          # item name wins: consumers display ItemStacks
    return entities, materials


def render(entities, materials):
    out = ["# Generated by harvest_vanilla.py from Mojang's client language files. Do not hand-edit.",
           "entity:"]
    for path in sorted(entities):
        out.append("  %s: %s" % (path, quote(entities[path])))
    out.append("material:")
    for path in sorted(materials):
        out.append("  %s: %s" % (path, quote(materials[path])))
    return "\n".join(out) + "\n"


def main():
    src_dir, langs_dir = sys.argv[1], sys.argv[2]
    filled = set()
    for locale, lang in sorted(LOCALES.items()):
        path = os.path.join(src_dir, locale + ".json")
        if not os.path.isfile(path):
            continue
        with io.open(path, encoding="utf-8") as handle:
            entities, materials = harvest(json.load(handle))
        if not entities and not materials:
            continue
        target = os.path.join(langs_dir, lang)
        os.makedirs(target, exist_ok=True)
        with io.open(os.path.join(target, "vanilla.yml"), "w", encoding="utf-8", newline="\n") as handle:
            handle.write(render(entities, materials))
        filled.add(lang)
        print("%-6s %4d entities %5d materials" % (lang, len(entities), len(materials)))

    expected = shipped_languages(langs_dir)
    missing = sorted(expected - filled)
    print("\n%d of %d Slimefun languages filled" % (len(filled & expected), len(expected)))
    if missing:
        print("NOT FILLED (these keep the English fallback): %s" % ", ".join(missing))


if __name__ == "__main__":
    main()
